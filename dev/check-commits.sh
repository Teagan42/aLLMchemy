#!/usr/bin/env bash
# Validates commit messages against Conventional Commits.
#
#   dev/check-commits.sh --message .git/COMMIT_EDITMSG   one message (the commit-msg hook)
#   dev/check-commits.sh --range origin/main..HEAD       every commit in a range (CI)
#   dev/check-commits.sh --title "feat: add a thing"     a PR title, header rules only
#
# Written here rather than pulled from npm because the repo has no package.json and no
# install step, and because release-please derives the next version from these messages:
# a malformed type silently produces no release rather than a wrong one. The commit-msg
# hook and CI run the same code, so the rule cannot drift between them.
#
# Squash-merging takes the PR TITLE as the commit subject, so CI checks that too. Checking
# only the branch commits lets a non-conforming subject reach main unopposed.

set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

# The types release-please understands. feat and fix move the version; the rest only land in
# the changelog, so an invented type is a silently unreleased change.
TYPES='feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert'
HEADER_RE="^($TYPES)(\([a-z0-9][a-z0-9._/-]*\))?!?: .+"
MAX_HEADER=72

fails=0
checked=0

usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; }

bad()  { printf '  FAIL  %s\n        %s\n' "$1" "$2"; fails=$((fails + 1)); }
good() { printf '  PASS  %s\n' "$1"; }

# Validates a header line. Shared by every mode, because a PR title and a commit subject are
# the same artifact after a squash merge.
check_header() {  # header, label
  ch_h=$1
  ch_label=$2
  ch_bad=0

  case "$ch_h" in
    # Merge commits are generated by git, not written, and the spec does not cover them.
    Merge\ *|Revert\ \"*) good "$ch_label (generated; skipped)"; return 0 ;;
  esac

  if ! printf '%s' "$ch_h" | grep -Eq -- "$HEADER_RE"; then
    bad "$ch_label" "not Conventional Commits: expected '<type>(<scope>)!: <description>'
        with type one of: $(printf '%s' "$TYPES" | tr '|' ' ')
        got: $ch_h"
    ch_bad=1
  fi

  ch_len=${#ch_h}
  if [ "$ch_len" -gt "$MAX_HEADER" ]; then
    bad "$ch_label" "header is $ch_len chars, over the $MAX_HEADER limit"
    ch_bad=1
  fi

  # A trailing period costs a character in a line already length-capped and reads oddly in a
  # generated changelog, where subjects become list items.
  case "$ch_h" in
    *.) bad "$ch_label" "subject ends with a period"; ch_bad=1 ;;
  esac

  # `type:` with nothing after it passes the regex via the space, so check the description
  # carries actual words.
  ch_desc=$(printf '%s' "$ch_h" | sed -E "s/^($TYPES)(\([^)]*\))?!?: //")
  if [ "${#ch_desc}" -lt 10 ]; then
    bad "$ch_label" "description '$ch_desc' is too short to say anything"
    ch_bad=1
  fi

  [ "$ch_bad" = 0 ] && good "$ch_label"
  return "$ch_bad"
}

# Body rules, which a PR title has no equivalent of.
#
# Takes the message as an ARGUMENT, not on stdin. A piped call runs in a subshell, where the
# `fails` increment is discarded and every body problem silently passes — the same trap
# bin/detect-question.sh documents for its pattern loop.
check_body() {  # label, full message
  cb_label=$1
  cb_msg=$2
  cb_second=$(printf '%s\n' "$cb_msg" | sed -n '2p')
  # Conventional Commits requires a blank line between header and body. Without it, git and
  # release-please both fold the first body line into the subject.
  if [ -n "$cb_second" ]; then
    bad "$cb_label" "line 2 must be blank, separating header from body"
    return 1
  fi
  # The spec spells this footer exactly; `breaking change:` lower-case is ignored, so a
  # genuine breaking change ships as a patch.
  if printf '%s\n' "$cb_msg" | grep -Eqi '^breaking[ -]change' \
     && ! printf '%s\n' "$cb_msg" | grep -Eq '^BREAKING CHANGE: '; then
    bad "$cb_label" "breaking-change footer must read exactly 'BREAKING CHANGE: <detail>'"
    return 1
  fi
  return 0
}

mode=
arg=
while [ $# -gt 0 ]; do
  case "$1" in
    --message|--range|--title) mode=${1#--}; shift; arg="${1:-}" ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'check-commits: unknown argument %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done

[ -n "$mode" ] || { usage >&2; exit 2; }

case "$mode" in
  title)
    [ -n "$arg" ] || { printf 'check-commits: --title needs a value\n' >&2; exit 2; }
    checked=1
    check_header "$arg" "PR title" || :
    ;;

  message)
    [ -f "$arg" ] || { printf 'check-commits: no such message file: %s\n' "$arg" >&2; exit 2; }
    # Strip git's instructional comments and anything below the scissors line, which are not
    # part of the message but would otherwise count as body.
    MSG=$(sed -E '/^# *-+ *>8 *-+/,$d' "$arg" | sed -E '/^#/d')
    HEADER=$(printf '%s\n' "$MSG" | sed -n '1p')
    [ -n "${HEADER// /}" ] || { printf 'check-commits: empty commit message\n' >&2; exit 1; }
    checked=1
    check_header "$HEADER" "commit message" || :
    check_body "commit message" "$MSG" || :
    ;;

  range)
    [ -n "$arg" ] || { printf 'check-commits: --range needs a value\n' >&2; exit 2; }
    # Subjects only, one per line, merges excluded. %s cannot contain a newline, so the loop
    # is safe without quoting gymnastics.
    SUBJECTS=$(git log --no-merges --format='%H %s' "$arg" 2>/dev/null) || {
      printf 'check-commits: cannot read range %s\n' "$arg" >&2; exit 2; }
    if [ -z "$SUBJECTS" ]; then
      printf 'check-commits: no non-merge commits in %s\n' "$arg"
      exit 0
    fi
    while IFS= read -r line; do
      [ -n "$line" ] || continue
      sha=${line%% *}
      subject=${line#* }
      checked=$((checked + 1))
      check_header "$subject" "$(printf '%.8s' "$sha")" || :
      check_body "$(printf '%.8s' "$sha")" "$(git log -1 --format='%B' "$sha")" || :
    done <<EOF
$SUBJECTS
EOF
    ;;
esac

printf '\n%s commit message(s) checked, %s problem(s).\n' "$checked" "$fails"
[ "$fails" -eq 0 ] || cat <<'EOF'

Conventional Commits, briefly:

  feat: add the thing          a feature      -> minor version bump
  fix: stop the crash          a bug fix      -> patch version bump
  feat!: drop the old flag     breaking       -> major version bump
  docs|test|ci|chore|refactor|perf|style|build|revert: ...   no version bump

  <type>(<optional scope>)!: <description>
  <blank line>
  <body: why, not what>
  <blank line>
  BREAKING CHANGE: <what breaks and what to do about it>

release-please reads these to decide the next version, so a wrong type does not fail
loudly — it ships the change with no release at all.
EOF
# Exit 1, not "$fails": an exit status wraps at 256, so 256 bad messages would exit 0 and
# report success. The count is in the summary line above where it cannot lie.
[ "$fails" -eq 0 ] || exit 1
exit 0
